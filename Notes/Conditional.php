Conditional Statement
    1. if statement: 
        statement is executed only if the expression evaluates to true.
        if(expression)
            statement;
    2. if...else statement: statement is executed if the expression evaluates to true, otherwise the else statement is executed. 
        if(expression)
            statement;
        else
            statement;
    3. if...elseif...else statement: statement is executed if the expression evaluates to true, otherwise the elseif statement is executed. If all the expressions evaluate to false, the else statement is executed.
        if(expression)
            statement;
        elseif(expression)
            statement;
        ..................
        elseif(expression)
            statement;
        else
            statement;